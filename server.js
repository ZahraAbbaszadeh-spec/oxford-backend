  `The learner is studying the lesson "${lesson.title}" (level ${lesson.level}, unit ${lesson.unit}) of Oxford Word Skills. ` +
  `Teach and converse ONLY around this lesson's words: ${lesson.words.join(", ")}. ` +
  `Speak mainly simple, clear English, and explain in Persian whenever the learner is stuck or asks in Persian. ` +
  `Keep replies short (2-4 sentences), ask one question at a time, gently correct mistakes, and always bring the conversation back to the lesson's words. ` +
  `Start by greeting the learner and using one of the lesson's words in a question if they say hello.`;

async function teacherReply({ lesson, history, message }) {
  const messages = [
    ...(history || []).slice(-12).map((h) => ({ role: h.role === "assistant" ? "model" : "user", text: String(h.text || "") })),
    { role: "user", text: String(message || "") },
  ];
  return generateText({ system: TEACHER_SYSTEM(lesson), messages, temperature: 0.8 });
}

