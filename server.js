const HOST = "generativelanguage.googleapis.com";
const key = () => process.env.GEMINI_API_KEY || "";
const geminiConfigured = () => key().length > 0;
const textModel = () => process.env.GEMINI_TEXT_MODEL || "gemini-3.5-flash";
const liveModel = () => process.env.GEMINI_LIVE_MODEL || "gemini-2.5-flash-native-audio-latest";

async function api(path, { method = "GET", body } = {}) {
  const r = await fetch(`https://${HOST}${path}`, {
    method,
    headers: { "x-goog-api-key": key(), "Content-Type": "application/json" },
    body: body ? JSON.stringify(body) : undefined,
  });
  const j = await r.json().catch(() => ({}));
  if (!r.ok) {
    const msg = j?.error?.message || `Gemini API HTTP ${r.status}`;
    const err = new Error(msg);
    err.status = r.status;
    throw err;
  }
  return j;
}

async function geminiCheck() {
  const j = await api("/v1beta/models");
  return { models: (j.models || []).length };
}

/** messages: [{role: "user"|"model", text}] */
async function generateText({ system, messages, json = false, temperature = 0.7 }) {
  const body = {
    contents: messages.map((m) => ({ role: m.role, parts: [{ text: m.text }] })),
    generationConfig: { temperature, ...(json ? { responseMimeType: "application/json" } : {}) },
  };
  if (system) body.systemInstruction = { parts: [{ text: system }] };
  const j = await api(`/v1beta/models/${textModel()}:generateContent`, { method: "POST", body });
  const parts = j?.candidates?.[0]?.content?.parts || [];
  return parts.map((p) => p.text || "").join("").trim();
}

/**
 * Persian meaning + one example sentence for a word. The books' word lists
 * carry no definitions, so — exactly like the Muse app — meanings are
 * generated by the model on first request and cached by the caller.
 */
async function generateMeaning(word) {
  const system =
    "You are the vocabulary engine of an English-learning app for Persian speakers. " +
    "For the given English word or phrase, reply with ONLY a JSON object: " +
    '{"meaning_fa": "<short, clear Persian meaning>", "example": "<one simple English example sentence using the word>"}';
  const out = await generateText({ system, messages: [{ role: "user", text: word }], json: true, temperature: 0.3 });
  let parsed;
  try { parsed = JSON.parse(out); } catch {
    const m = out.match(/\{[\s\S]*\}/);
    if (m) parsed = JSON.parse(m[0]);
  }
  if (!parsed?.meaning_fa || !parsed?.example) throw new Error("meaning_generation_failed");
  return { meaning_fa: String(parsed.meaning_fa), example: String(parsed.example), model: textModel() };
}

