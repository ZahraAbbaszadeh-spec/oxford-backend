// ---------- helpers ----------
function json(res, status, obj) {
  const body = JSON.stringify(obj);
  res.writeHead(status, { "Content-Type": "application/json; charset=utf-8" });
  res.end(body);
}
async function readBody(req) {
  const chunks = [];
  for await (const c of req) chunks.push(c);
  if (!chunks.length) return {};
  try { return JSON.parse(Buffer.concat(chunks).toString("utf8")); } catch { return {}; }
}
function getLesson(level, unit) {
  const lesson = db.prepare("SELECT * FROM lessons WHERE level = ? AND unit = ?").get(level, unit);
  if (!lesson) return null;
  const words = db.prepare("SELECT id, word FROM words WHERE level = ? AND unit = ? ORDER BY word").all(level, unit);
  return { ...lesson, words: words.map((w) => w.word), wordRows: words };
}
const aiUnavailable = (res) => json(res, 503, { error: "gemini_not_configured", detail: "Set GEMINI_API_KEY on the server to enable AI features." });

// ---------- routes ----------
const server = createServer(async (req, res) => {
  const url = new URL(req.url, "http://localhost");
  const path = url.pathname;
  try {
    if (path === "/health") {
      const { c: lessons } = db.prepare("SELECT COUNT(*) AS c FROM lessons").get();
      const { c: words } = db.prepare("SELECT COUNT(*) AS c FROM words").get();
      return json(res, 200, { ok: true, service: "oxford-vocab-backend", lessons, words, geminiConfigured: geminiConfigured() });
    }
    if (path === "/api/system/gemini-check") {
      if (!geminiConfigured()) return aiUnavailable(res);
      const check = await geminiCheck();
      return json(res, 200, { ok: true, ...check });
    }
    if (path === "/api/levels") {
      const rows = db.prepare(`
        SELECT l.level, l.unit, l.section, l.title, l.page, COUNT(w.id) AS wordCount
        FROM lessons l LEFT JOIN words w ON w.level = l.level AND w.unit = l.unit
        GROUP BY l.level, l.unit ORDER BY l.level, l.unit`).all();
      return json(res, 200, { levels: [2, 3].map((level) => ({ level, units: rows.filter((r) => r.level === level) })) });
    }
    const lessonMatch = path.match(/^\/api\/lessons\/(\d+)\/(\d+)$/);
    if (lessonMatch) {
      const lesson = getLesson(Number(lessonMatch[1]), Number(lessonMatch[2]));
      if (!lesson) return json(res, 404, { error: "lesson_not_found" });
      return json(res, 200, { level: lesson.level, unit: lesson.unit, section: lesson.section, title: lesson.title, page: lesson.page, words: lesson.wordRows });
    }
    if (path === "/api/signup" && req.method === "POST") {
      const { name } = await readBody(req);
      const user = findOrCreateUser(db, name);
      if (!user) return json(res, 400, { error: "name_required" });
      return json(res, 200, { user: { id: user.id, name: user.name }, progress: getProgress(db, user.id) });
    }
    const userMatch = path.match(/^\/api\/users\/(\d+)\/(progress|goal|complete|leitner\/(due|review))$/);
    if (userMatch) {
      const userId = Number(userMatch[1]);
      const user = db.prepare("SELECT * FROM users WHERE id = ?").get(userId);
      if (!user) return json(res, 404, { error: "user_not_found" });
      const action = userMatch[2];
      if (action === "progress") return json(res, 200, { user: { id: user.id, name: user.name }, progress: getProgress(db, userId) });
      if (action === "goal" && req.method === "POST") {
        const { dailyGoal } = await readBody(req);
        const goal = Math.max(1, Math.min(500, Number(dailyGoal) || 20));
        db.prepare("UPDATE progress SET daily_goal = ? WHERE user_id = ?").run(goal, userId);
        return json(res, 200, { progress: getProgress(db, userId) });
      }
      if (action === "complete" && req.method === "POST") {
        const { level, unit } = await readBody(req);
        const result = completeLesson(db, userId, Number(level), Number(unit));
        if (!result) return json(res, 404, { error: "lesson_not_found" });
        return json(res, 200, { xpAwarded: result.xpAwarded, enrolledNew: result.enrolledNew, progress: result.progress });
      }
      if (action === "leitner/due") return json(res, 200, { due: dueWords(db, userId, Number(url.searchParams.get("limit") || 50)) });
      if (action === "leitner/review" && req.method === "POST") {
        const { wordId, correct } = await readBody(req);
        const result = reviewWord(db, userId, Number(wordId), !!correct);
        if (!result) return json(res, 404, { error: "word_not_enrolled" });
        return json(res, 200, { ...result, progress: getProgress(db, userId) });
      }
    }
    if (path === "/api/meaning") {
      const word = (url.searchParams.get("word") || "").trim();
      if (!word) return json(res, 400, { error: "word_required" });
      const cached = db.prepare("SELECT * FROM meanings WHERE word = ?").get(word.toLowerCase());
      if (cached) return json(res, 200, { word, meaning_fa: cached.meaning_fa, example: cached.example, cached: true });
      if (!geminiConfigured()) return aiUnavailable(res);
      const gen = await generateMeaning(word);
      db.prepare("INSERT OR REPLACE INTO meanings (word, meaning_fa, example, model, created_at) VALUES (?, ?, ?, ?, ?)")
        .run(word.toLowerCase(), gen.meaning_fa, gen.example, gen.model, new Date().toISOString());
      return json(res, 200, { word, meaning_fa: gen.meaning_fa, example: gen.example, cached: false });
    }
    if (path === "/api/teacher/chat" && req.method === "POST") {
      if (!geminiConfigured()) return aiUnavailable(res);
      const { level, unit, message, history } = await readBody(req);
      const lesson = getLesson(Number(level), Number(unit));
      if (!lesson) return json(res, 404, { error: "lesson_not_found" });
      if (!message) return json(res, 400, { error: "message_required" });
      const reply = await teacherReply({ lesson, history, message });
      return json(res, 200, { reply });
    }
    // static status page: index.html sits in the bundle root next to server.js
    if (path === "/" || path === "/index.html") {
      try {
        const data = await readFile(join(root, "index.html"));
        res.writeHead(200, { "Content-Type": "text/html; charset=utf-8" });
        return res.end(data);
      } catch { /* fall through to 404 */ }
    }
    return json(res, 404, { error: "not_found" });
  } catch (e) {
    return json(res, 500, { error: "server_error", detail: String(e.message || e) });
  }
});

attachLiveRelay(server, { getLesson });
server.listen(PORT, () => console.log(`oxford-vocab-backend listening on :${PORT} (gemini configured: ${geminiConfigured()})`));
